function regionName(code, language) {
  try { return new Intl.DisplayNames([language],{type:'region'}).of(code); }
  catch { return code; }
}

function tr(value, language=state.language) {
  if (!value || language==='de') return value;
  return translations[value]?.[language==='en'?0:1]||value;
}

